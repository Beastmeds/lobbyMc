    static String translate(String value,String language){
        if(!language.equals("de"))return value;
        String exact=DE.get(value);if(exact!=null)return exact;
        // Localize complete UI phrases and fixed prefixes without translating player names.
        for(String separator:List.of(" · "," → "))if(value.contains(separator))return String.join(separator,Arrays.stream(value.split(java.util.regex.Pattern.quote(separator),-1)).map(v->translate(v,language)).toList());
        for(var e:DE.entrySet().stream().sorted((a,b)->Integer.compare(b.getKey().length(),a.getKey().length())).toList()){
            String key=e.getKey();
            if((key.endsWith(": ")||key.equals("Welcome back")||key.equals("Pumpkin found! ")||key.equals("Connecting to "))&&value.startsWith(key)){
                String tail=value.substring(key.length());return e.getValue()+DE.getOrDefault(tail,tail);
            }
            if(key.startsWith(" ")&&value.endsWith(key))return value.substring(0,value.length()-key.length())+e.getValue();
        }
        return value;
    }
